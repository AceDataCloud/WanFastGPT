import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs, isDeepStrictEqual } from 'node:util';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OPERATION = {"apiId": "6a4ecdbf-b219-4505-8277-5ec4b1ac14f8", "path": "/wan/videos", "supportedFields": ["model", "action", "prompt", "duration", "resolution", "ratio", "audio", "image_url", "reference_video_urls", "audio_url", "media", "async"], "actions": ["text2video", "image2video"], "mediaTypes": true};
function values(schema) {
  const list = schema?.enum;
  if (!Array.isArray(list) || !list.length || list.some(x => typeof x !== 'string') || new Set(list).size !== list.length) throw new Error('Expected a nonempty unique string enum; existing catalog is preserved.');
  return list;
}
export function project(spec) {
  const schema = spec.paths?.[OPERATION.path]?.post?.requestBody?.content?.['application/json']?.schema;
  if (!schema?.properties || (schema.required ?? []).some(x => !OPERATION.supportedFields.includes(x))) throw new Error('Required API inputs changed; review the plugin before refreshing.');
  const result = { models: values(schema.properties.model) };
  if (OPERATION.actions.length) {
    const published = values(schema.properties.action);
    if (OPERATION.actions.some(x => !published.includes(x))) throw new Error('A supported generation mode disappeared.');
    result.actions = OPERATION.actions;
  }
  if (OPERATION.mediaTypes) result.mediaTypes = values(schema.properties.media?.items?.properties?.type);
  return result;
}
export function render(catalog) {
  const lines = ['// Generated by scripts/sync-model-catalog.mjs. Do not edit.'];
  for (const [name, list] of Object.entries(catalog)) {
    values({ enum: list });
    lines.push(`export const ${name.replace(/[A-Z]/g, x => '_' + x).toUpperCase()} = ${JSON.stringify(list, null, 2)} as const;`);
  }
  lines.push("export const MODEL_HELP = 'Current published models: ' + MODELS.join(', ') + '. Choose a mode and reference inputs supported by the model.';");
  return lines.join('\n') + '\n';
}
async function main() {
  const { values: args } = parseArgs({ options: { refresh: { type: 'boolean' }, check: { type: 'boolean' } } });
  const snapshotPath = resolve(root, 'contracts/model-catalog.json');
  const outputPath = resolve(root, 'src/model-catalog.ts');
  const existing = JSON.parse(await readFile(snapshotPath, 'utf8'));
  let snapshot = existing;
  if (args.refresh) {
    const response = await fetch(`https://platform.acedata.cloud/api/v1/apis/${OPERATION.apiId}/`, { signal: AbortSignal.timeout(30000) });
    if (!response.ok) throw new Error(`Public contract request failed: HTTP ${response.status}`);
    const catalog = project((await response.json()).definition);
    if (!isDeepStrictEqual(catalog, existing.catalog)) snapshot = { source: { apiId: OPERATION.apiId, path: OPERATION.path }, catalog };
  }
  const generated = render(snapshot.catalog);
  if (args.check) {
    if (await readFile(outputPath, 'utf8') !== generated) throw new Error('Generated model catalog is stale.');
  } else {
    await writeFile(snapshotPath, JSON.stringify(snapshot, null, 2) + '\n');
    await writeFile(outputPath, generated);
  }
  console.log(JSON.stringify({ models: snapshot.catalog.models.length }));
}
